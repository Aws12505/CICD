<?php

namespace App\Services\Provision;

use App\Models\Server;

/**
 * The shared MySQL, Redis and NATS that every stack on a server uses.
 *
 * One set per server, joined by both tiers (decision 8). They publish no
 * ports at all: services reach them by name over the `pizza_shared` Docker
 * network, and nothing outside the machine can.
 */
class InfraRenderer
{
    public const ROOT = '/srv/_infra';

    public const MYSQL_IMAGE = 'mysql:8.4';

    public const REDIS_IMAGE = 'redis:7.4';

    public const NATS_IMAGE = 'nats:2.10-alpine';

    /**
     * Files to write, path => [contents, mode, writeOnce].
     *
     * Redis's ACL file is written once and then owned by Redis: stack users
     * are added with ACL SETUSER and saved by ACL SAVE, and rewriting the file
     * would delete them.
     *
     * @return array<string, array{0: string, 1: string, 2: bool}>
     */
    public function files(Server $server): array
    {
        return [
            self::ROOT.'/docker-compose.yml' => [$this->compose(), '644', false],
            self::ROOT.'/mysql.env' => [
                'MYSQL_ROOT_PASSWORD='.$server->secret('mysql_root')."\n",
                '600', false,
            ],
            self::ROOT.'/redis.env' => [
                // Not read by Redis itself; lets `redis-cli` inside the
                // container authenticate without the password on a command line.
                'REDIS_ROOT_PASSWORD='.$server->secret('redis_root')."\n",
                '600', false,
            ],
            self::ROOT.'/nats.conf' => [$this->natsConfig($server), '600', false],
            self::ROOT.'/redis/users.acl' => [
                'user default on >'.$server->secret('redis_root')." ~* &* +@all\n",
                '600', true,
            ],
        ];
    }

    public function compose(): string
    {
        $root = self::ROOT;
        $mysql = self::MYSQL_IMAGE;
        $redis = self::REDIS_IMAGE;
        $nats = self::NATS_IMAGE;

        return <<<YAML
        # Generated by the control plane. Shared by every stack on this server.
        name: pizza_infra

        services:
          mysql:
            image: {$mysql}
            container_name: mysql
            restart: unless-stopped
            env_file: ./mysql.env
            command:
              - --character-set-server=utf8mb4
              - --collation-server=utf8mb4_unicode_ci
            volumes:
              - {$root}/mysql:/var/lib/mysql
            healthcheck:
              test: ["CMD-SHELL", "mysqladmin ping -uroot -p\"\$\$MYSQL_ROOT_PASSWORD\" --silent"]
              interval: 10s
              timeout: 5s
              retries: 30
            networks: [shared]

          redis:
            image: {$redis}
            container_name: redis
            restart: unless-stopped
            env_file: ./redis.env
            command: ["redis-server", "--aclfile", "/data/users.acl", "--appendonly", "yes"]
            volumes:
              - {$root}/redis:/data
            networks: [shared]

          nats:
            image: {$nats}
            container_name: nats
            restart: unless-stopped
            command: ["-c", "/etc/nats/nats.conf"]
            volumes:
              - {$root}/nats:/data
              - {$root}/nats.conf:/etc/nats/nats.conf:ro
            networks: [shared]

        networks:
          shared:
            external: true
            name: pizza_shared

        YAML;
    }

    private function natsConfig(Server $server): string
    {
        $token = $server->secret('nats_token');

        return <<<CONF
        # Generated by the control plane.
        port: 4222
        http_port: 8222
        jetstream {
          store_dir: /data
        }
        authorization {
          token: "{$token}"
        }

        CONF;
    }
}
