<?php

namespace App\Services\Provision;

use App\Models\Server;

/**
 * The shared MySQL, Redis and NATS that every stack on a server uses.
 *
 * One set per server, joined by both tiers (decision 8). They publish no
 * ports at all: services reach them by name over the `pizza_shared` Docker
 * network, and nothing outside the machine can.
 */
class InfraRenderer
{
    public const ROOT = '/srv/_infra';

    public const MYSQL_IMAGE = 'mysql:8.4';

    public const REDIS_IMAGE = 'redis:7.4';

    public const NATS_IMAGE = 'nats:2.10-alpine';

    /**
     * Files to write, path => [contents, mode, writeOnce].
     *
     * Redis's ACL file is written once and then owned by Redis: stack users
     * are added with ACL SETUSER and saved by ACL SAVE, and rewriting the file
     * would delete them.
     *
     * @param  int  $memoryKb  the server's RAM, for MySQL's buffer pool (0: unknown)
     * @param  int  $maxConnections  the starting ceiling; releases keep it current
     * @return array<string, array{0: string, 1: string, 2: bool}>
     */
    public function files(Server $server, int $memoryKb = 0, int $maxConnections = MysqlSizing::MINIMUM): array
    {
        return [
            self::ROOT.'/docker-compose.yml' => [$this->compose(), '644', false],
            // 644: MySQL ignores a world-writable option file.
            self::ROOT.'/mysql.cnf' => [$this->mysqlConfig($memoryKb, $maxConnections), '644', false],
            self::ROOT.'/mysql.env' => [
                'MYSQL_ROOT_PASSWORD='.$server->secret('mysql_root')."\n",
                '600', false,
            ],
            self::ROOT.'/redis.env' => [
                // Not read by Redis itself; lets `redis-cli` inside the
                // container authenticate without the password on a command line.
                'REDIS_ROOT_PASSWORD='.$server->secret('redis_root')."\n",
                '600', false,
            ],
            self::ROOT.'/nats.conf' => [$this->natsConfig($server), '600', false],
            self::ROOT.'/redis/users.acl' => [
                'user default on >'.$server->secret('redis_root')." ~* &* +@all\n",
                '600', true,
            ],
        ];
    }

    public function compose(): string
    {
        $root = self::ROOT;
        $mysql = self::MYSQL_IMAGE;
        $redis = self::REDIS_IMAGE;
        $nats = self::NATS_IMAGE;

        return <<<YAML
        # Generated by the control plane. Shared by every stack on this server.
        name: pizza_infra

        services:
          mysql:
            image: {$mysql}
            container_name: mysql
            restart: unless-stopped
            env_file: ./mysql.env
            command:
              - --character-set-server=utf8mb4
              - --collation-server=utf8mb4_unicode_ci
            ulimits:
              nofile: {soft: 65535, hard: 65535}
            volumes:
              - {$root}/mysql:/var/lib/mysql
              - {$root}/mysql.cnf:/etc/mysql/conf.d/control-plane.cnf:ro
            healthcheck:
              test: ["CMD-SHELL", "mysqladmin ping -uroot -p\"\$\$MYSQL_ROOT_PASSWORD\" --silent"]
              interval: 10s
              timeout: 5s
              retries: 30
            stop_grace_period: 60s
            logging: &logging
              driver: json-file
              options: {max-size: "10m", max-file: "3"}
            networks: [shared]

          redis:
            image: {$redis}
            container_name: redis
            restart: unless-stopped
            env_file: ./redis.env
            command: ["redis-server", "--aclfile", "/data/users.acl", "--appendonly", "yes"]
            volumes:
              - {$root}/redis:/data
            healthcheck:
              test: ["CMD-SHELL", "REDISCLI_AUTH=\"\$\$REDIS_ROOT_PASSWORD\" redis-cli --user default ping | grep -q PONG"]
              interval: 10s
              timeout: 5s
              retries: 10
            logging: *logging
            networks: [shared]

          nats:
            image: {$nats}
            container_name: nats
            restart: unless-stopped
            command: ["-c", "/etc/nats/nats.conf"]
            volumes:
              - {$root}/nats:/data
              - {$root}/nats.conf:/etc/nats/nats.conf:ro
            healthcheck:
              test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8222/healthz"]
              interval: 10s
              timeout: 5s
              retries: 10
            logging: *logging
            networks: [shared]

        networks:
          shared:
            external: true
            name: pizza_shared

        YAML;
    }

    /**
     * MySQL tuned for many short-lived connections from many services.
     *
     * max_connections here is only the starting value: every release sets the
     * current one with SET PERSIST (MysqlSizing), which wins over this file.
     * Per-connection buffers stay at their defaults; they are allocated only
     * while a query needs them, which is what keeps a high ceiling cheap.
     */
    public function mysqlConfig(int $memoryKb, int $maxConnections): string
    {
        // About 40% of the server's RAM; the rest is for the services.
        $bufferPool = $memoryKb > 0
            ? max(256, (int) floor($memoryKb / 1024 * (float) config('deploy.mysql.buffer_pool_ratio', 0.4) / 128) * 128)
            : 512;

        return <<<CNF
        # Generated by the control plane.
        [mysqld]
        max_connections = {$maxConnections}
        max_connect_errors = 100000
        thread_cache_size = 256
        table_open_cache = 8000
        table_definition_cache = 4000
        open_files_limit = 65535
        innodb_buffer_pool_size = {$bufferPool}M
        # Reap connections a process opened and forgot; Laravel reconnects on
        # its next query.
        wait_timeout = 600
        interactive_timeout = 600
        skip-name-resolve

        CNF;
    }

    private function natsConfig(Server $server): string
    {
        $token = $server->secret('nats_token');

        return <<<CONF
        # Generated by the control plane.
        port: 4222
        http_port: 8222
        jetstream {
          store_dir: /data
        }
        authorization {
          token: "{$token}"
        }

        CONF;
    }
}
