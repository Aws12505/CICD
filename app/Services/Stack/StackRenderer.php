<?php

namespace App\Services\Stack;

use App\Models\Stack;
use App\Models\StackService;
use Illuminate\Support\Collection;

/**
 * Turns database rows into the files that actually run on a client's server.
 *
 * Everything this writes is derived. Nothing on a client machine should be
 * hand-edited, because the drift poller exists to notice when it has been.
 */
class StackRenderer
{
    public function __construct(
        private readonly EnvResolver $env,
        private readonly PortAllocator $ports,
    ) {}

    /**
     * Every file this stack needs, keyed by path relative to the stack root.
     *
     * @return array<string, string>
     */
    public function files(Stack $stack): array
    {
        $enabled = $this->enabledServices($stack);

        $files = ['docker-compose.yml' => $this->compose($stack, $enabled)];

        foreach ($enabled as $entitlement) {
            $files['env/'.$entitlement->service->slug.'.env'] = $this->env($entitlement);
            $domain = $stack->domainFor($entitlement->service);
            // Both are written; StackSync::reloadNginx links the TLS one once
            // the certificate exists and the plain one until then.
            $files['nginx/'.$domain.'.conf'] = $this->nginx($entitlement);
            $files['nginx/'.$domain.'.http'] = $this->nginxHttpOnly($entitlement);
        }

        return $files;
    }

    /** Absolute path of this stack's directory on its server. */
    public function rootPath(Stack $stack): string
    {
        return rtrim(config('deploy.root'), '/').'/'.$stack->compose_project;
    }

    /**
     * @param  Collection<int, StackService>|null  $enabled
     */
    public function compose(Stack $stack, ?Collection $enabled = null): string
    {
        $enabled ??= $this->enabledServices($stack);
        $root = $this->rootPath($stack);

        $lines = [
            '# Generated by the control plane. Do not edit on the server —',
            '# the drift poller will flag it and a release will overwrite it.',
            'name: '.$stack->compose_project,
            '',
            'services:',
        ];

        foreach ($enabled as $entitlement) {
            $service = $entitlement->service;
            $port = $this->ports->assign($entitlement);

            $lines[] = '  '.$service->slug.':';
            $lines[] = '    image: '.$this->imageReference($entitlement);
            $lines[] = '    container_name: '.$entitlement->containerName();
            $lines[] = '    env_file:';
            $lines[] = '      - ./env/'.$service->slug.'.env';
            $lines[] = '    ports:';
            $lines[] = '      - "127.0.0.1:'.$port.':'.$this->containerPort($service->build_recipe).'"';
            $lines[] = '    volumes:';
            // A host bind path rather than a named volume, so the weekly rsync
            // backup can read it directly.
            $lines[] = '      - '.$root.'/storage/'.$service->slug.':'.$this->storagePath($service->build_recipe);
            $lines[] = '    restart: unless-stopped';
            $lines[] = '    networks:';
            $lines[] = '      - shared';

            foreach ($service->processList() as $process) {
                $lines[] = '  '.$service->slug.'_'.$process['name'].':';
                $lines[] = '    image: '.$this->imageReference($entitlement);
                $lines[] = '    container_name: '.$entitlement->containerName().'_'.$process['name'];
                // JSON is valid YAML, and quotes whatever the command holds.
                $lines[] = '    command: '.json_encode(
                    $process['command'] === null ? ['worker'] : ['sh', '-c', $process['command']],
                    JSON_UNESCAPED_SLASHES,
                );

                if ($process['port'] !== null) {
                    $lines[] = '    ports:';
                    $lines[] = '      - "127.0.0.1:'.$this->ports->assignProcess($entitlement, $process['name']).':'.$process['port'].'"';
                }
                $lines[] = '    env_file:';
                $lines[] = '      - ./env/'.$service->slug.'.env';
                $lines[] = '    volumes:';
                $lines[] = '      - '.$root.'/storage/'.$service->slug.':'.$this->storagePath($service->build_recipe);
                $lines[] = '    restart: unless-stopped';
                $lines[] = '    networks:';
                $lines[] = '      - shared';
            }
        }

        if ($enabled->isEmpty()) {
            $lines[] = '  {}';
        }

        $lines[] = '';
        $lines[] = 'networks:';
        $lines[] = '  shared:';
        // MySQL, Redis and NATS are one shared set per server, joined by both
        // tiers. They are created by provisioning, not by this file.
        $lines[] = '    external: true';
        $lines[] = '    name: '.config('deploy.shared_network', 'pizza_shared');

        return implode("\n", $lines)."\n";
    }

    /**
     * The .env file for one service on one stack.
     *
     * Secrets land here in plaintext, on the client's own disk, because the
     * container has to read them. The file is written 0600 by the deploy.
     */
    public function env(StackService $entitlement): string
    {
        $lines = [
            '# Generated by the control plane. Do not edit on the server.',
        ];

        foreach ($this->env->resolve($entitlement) as $key => $value) {
            $lines[] = $key.'='.$this->quote((string) $value);
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * An nginx vhost, matching the shape already in use on the current
     * server so a migrated host looks familiar.
     *
     * TLS settings are written out here rather than included from the files
     * certbot's nginx plugin creates: certificates are issued with
     * `certonly --webroot`, which never creates them.
     */
    public function nginx(StackService $entitlement, bool $maintenance = false): string
    {
        $domain = $entitlement->stack->domainFor($entitlement->service);
        $body = $this->locationBody($entitlement, $maintenance);
        $acme = $this->acmeLocation();
        $processes = $maintenance ? '' : $this->processLocations($entitlement);

        return <<<CONF
        # Generated by the control plane. Do not edit on the server.
        server {
            server_name {$domain};

            client_max_body_size 500m;
        {$processes}
            location / {
        {$body}
            }

            # `listen ... http2` rather than `http2 on`: Ubuntu 24.04 and
            # Debian 12 ship nginx older than 1.25.1, which lacks the latter.
            listen 443 ssl http2;
            listen [::]:443 ssl http2;

            ssl_certificate /etc/letsencrypt/live/{$domain}/fullchain.pem;
            ssl_certificate_key /etc/letsencrypt/live/{$domain}/privkey.pem;
            ssl_protocols TLSv1.2 TLSv1.3;
            ssl_prefer_server_ciphers off;
            ssl_session_cache shared:SSL:10m;
            ssl_session_timeout 1d;
        }

        server {
            listen 80;
            listen [::]:80;
            server_name {$domain};

        {$acme}

            location / {
                return 301 https://\$host\$request_uri;
            }
        }

        CONF;
    }

    /**
     * Until the certificate exists: answer the ACME challenge, and serve the
     * service over plain HTTP so a fresh testing stack can be checked while
     * DNS and certificates catch up.
     */
    public function nginxHttpOnly(StackService $entitlement): string
    {
        $domain = $entitlement->stack->domainFor($entitlement->service);
        $body = $this->locationBody($entitlement, false);
        $acme = $this->acmeLocation();
        $processes = $this->processLocations($entitlement);

        return <<<CONF
        # Generated by the control plane. Used until {$domain} has a certificate.
        server {
            listen 80;
            listen [::]:80;
            server_name {$domain};

            client_max_body_size 500m;
        {$processes}
        {$acme}

            location / {
        {$body}
            }
        }

        CONF;
    }

    private function locationBody(StackService $entitlement, bool $maintenance): string
    {
        if ($maintenance) {
            return <<<'CONF'
                    # Maintenance window in progress — set by the release runner.
                    root /var/www/maintenance;
                    try_files /index.html =503;
            CONF;
        }

        $port = $this->ports->assign($entitlement);

        return <<<CONF
                proxy_pass http://127.0.0.1:{$port};
                proxy_http_version 1.1;

                proxy_set_header Host              \$host;
                proxy_set_header X-Real-IP         \$remote_addr;
                proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
                proxy_set_header X-Forwarded-Proto \$scheme;
                proxy_set_header Upgrade           \$http_upgrade;
                proxy_set_header Connection        \$connection_upgrade;

                proxy_connect_timeout 600s;
                proxy_send_timeout 600s;
                proxy_read_timeout 600s;
                send_timeout 600s;
        CONF;
    }

    /**
     * A location per listening process: Reverb's websocket at /app, with
     * the upgrade headers and a long read timeout.
     */
    private function processLocations(StackService $entitlement): string
    {
        $out = '';

        foreach ($entitlement->service->processList() as $process) {
            if ($process['port'] === null || $process['path'] === null) {
                continue;
            }

            $port = $this->ports->assignProcess($entitlement, $process['name']);

            $out .= <<<CONF

                location {$process['path']} {
                    proxy_pass http://127.0.0.1:{$port};
                    proxy_http_version 1.1;
                    proxy_set_header Host              \$host;
                    proxy_set_header X-Real-IP         \$remote_addr;
                    proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
                    proxy_set_header X-Forwarded-Proto \$scheme;
                    proxy_set_header Upgrade           \$http_upgrade;
                    proxy_set_header Connection        \$connection_upgrade;
                    proxy_read_timeout 1d;
                }

            CONF;
        }

        return $out;
    }

    /** Certificate issue and renewal both answer from this webroot. */
    private function acmeLocation(): string
    {
        return <<<'CONF'
            location ^~ /.well-known/acme-challenge/ {
                root /var/www/acme;
                default_type text/plain;
            }
        CONF;
    }

    /**
     * Pinned to a digest whenever one is known.
     *
     * A tag can be repointed at different bytes; a digest cannot. Pulling by
     * digest is what makes "the same image ran on testing and live" a fact
     * rather than a claim.
     */
    public function imageReference(StackService $entitlement): string
    {
        $repository = $entitlement->service->imageRepository();

        if (filled($entitlement->desired_digest)) {
            return $repository.'@'.$entitlement->desired_digest;
        }

        // Nothing has been built for this stack yet.
        return $repository.':'.($entitlement->edition ?: 'latest');
    }

    /**
     * @return Collection<int, StackService>
     */
    private function enabledServices(Stack $stack): Collection
    {
        return StackService::query()
            ->with('service', 'stack.client')
            ->where('stack_id', $stack->id)
            ->where('enabled', true)
            ->get()
            ->sortBy(fn (StackService $s) => [$s->service->position, $s->service->slug])
            ->values();
    }

    private function containerPort(string $recipe): int
    {
        return $recipe === 'nextjs' ? 3000 : 80;
    }

    private function storagePath(string $recipe): string
    {
        return $recipe === 'nextjs'
            ? '/app/.next/cache'
            : '/var/www/html/storage/app';
    }

    /**
     * Quote only when the value needs it. Docker's env_file parser does not
     * strip quotes the way a shell does, so quoting everything would embed
     * literal quote characters in the values.
     */
    private function quote(string $value): string
    {
        return preg_match('/^[A-Za-z0-9_.:\/@=+-]*$/', $value) === 1
            ? $value
            : '"'.str_replace(['\\', '"'], ['\\\\', '\"'], $value).'"';
    }
}
