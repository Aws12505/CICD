<?php

namespace App\Services\Stack;

use App\Models\Service;
use App\Models\Stack;
use App\Models\StackService;
use App\Services\Build\BuildFiles;
use Illuminate\Support\Collection;

/**
 * Turns database rows into the files that actually run on a client's server.
 *
 * Everything this writes is derived. Nothing on a client machine should be
 * hand-edited, because the drift poller exists to notice when it has been.
 *
 * The compose blocks and the TLS vhost come from each service's templates
 * (decision 27): the control plane's defaults unless the service overrides
 * them. The placeholders are filled here, per stack.
 */
class StackRenderer
{
    public function __construct(
        private readonly EnvResolver $env,
        private readonly PortAllocator $ports,
        private readonly BuildFiles $files,
    ) {}

    /**
     * Every file this stack needs, keyed by path relative to the stack root.
     *
     * @return array<string, string>
     */
    public function files(Stack $stack): array
    {
        $enabled = $this->enabledServices($stack);

        $files = ['docker-compose.yml' => $this->compose($stack, $enabled)];

        foreach ($enabled as $entitlement) {
            $files['env/'.$entitlement->service->slug.'.env'] = $this->env($entitlement);
            $domain = $stack->domainFor($entitlement->service);
            // Both are written; StackSync::reloadNginx links the TLS one once
            // the certificate exists and the plain one until then.
            $files['nginx/'.$domain.'.conf'] = $this->nginx($entitlement);
            $files['nginx/'.$domain.'.http'] = $this->nginxHttpOnly($entitlement);
        }

        return $files;
    }

    /** Absolute path of this stack's directory on its server. */
    public function rootPath(Stack $stack): string
    {
        return rtrim(config('deploy.root'), '/').'/'.$stack->compose_project;
    }

    /**
     * The stack's docker-compose.yml: a header, each enabled service's web
     * block and one block per process, and the shared network.
     *
     * @param  Collection<int, StackService>|null  $enabled
     */
    public function compose(Stack $stack, ?Collection $enabled = null): string
    {
        $enabled ??= $this->enabledServices($stack);

        $out = "# Generated by the control plane. Do not edit on the server —\n"
            ."# the drift poller will flag it and a release will overwrite it.\n"
            .'name: '.$stack->compose_project."\n\nservices:\n";

        foreach ($enabled as $entitlement) {
            $out .= $this->serviceBlock($entitlement);

            foreach ($entitlement->service->processList() as $process) {
                $out .= $this->processBlock($entitlement, $process);
            }
        }

        if ($enabled->isEmpty()) {
            $out .= "  {}\n";
        }

        // MySQL, Redis and NATS are one shared set per server, joined by both
        // tiers. They are created by provisioning, not by this file.
        return $out."\nnetworks:\n  shared:\n    external: true\n    name: ".$this->network()."\n";
    }

    /**
     * The .env file for one service on one stack.
     *
     * Secrets land here in plaintext, on the client's own disk, because the
     * container has to read them. The file is written 0600 by the deploy.
     */
    public function env(StackService $entitlement): string
    {
        $lines = [
            '# Generated by the control plane. Do not edit on the server.',
        ];

        foreach ($this->env->resolve($entitlement) as $key => $value) {
            $lines[] = $key.'='.$this->quote((string) $value);
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * The TLS vhost, from the service's nginx template. In maintenance the
     * generated page replaces it: that one must always be valid, whatever
     * the template says.
     */
    public function nginx(StackService $entitlement, bool $maintenance = false): string
    {
        $service = $entitlement->service;
        $domain = $entitlement->stack->domainFor($service);

        if ($maintenance) {
            return $this->maintenanceVhost($domain, tls: true);
        }

        $template = $this->files->resolve($service, BuildFiles::NGINX) ?? '';

        return $this->files->render($template, [
            'domain' => $domain,
            'host_port' => $this->ports->assign($entitlement),
            'cert_dir' => '/etc/letsencrypt/live/'.$domain,
        ], [
            'acme_location' => $this->acmeLocation(),
            'process_locations' => $this->processLocations($entitlement),
        ]);
    }

    /**
     * Until the certificate exists: answer the ACME challenge, and serve the
     * service over plain HTTP so a fresh testing stack can be checked while
     * DNS and certificates catch up. Always generated: the template may be
     * wrong, and this one has to stand in for it.
     */
    public function nginxHttpOnly(StackService $entitlement, bool $maintenance = false): string
    {
        $domain = $entitlement->stack->domainFor($entitlement->service);

        if ($maintenance) {
            return $this->maintenanceVhost($domain, tls: false);
        }

        $port = $this->ports->assign($entitlement);
        $acme = $this->indent($this->acmeLocation(), 4);
        $processes = $this->indent($this->processLocations($entitlement), 4);

        return "# Generated by the control plane. Used until {$domain} has a certificate.\n"
            ."server {\n"
            ."    listen 80;\n"
            ."    listen [::]:80;\n"
            ."    server_name {$domain};\n\n"
            ."    client_max_body_size 500m;\n"
            .($processes === '' ? '' : "\n".$processes)
            ."\n".$acme."\n"
            ."    location / {\n"
            .$this->indent($this->proxyBody($port), 8)
            ."    }\n"
            ."}\n";
    }

    /**
     * Pinned to a digest whenever one is known.
     *
     * A tag can be repointed at different bytes; a digest cannot. Pulling by
     * digest is what makes "the same image ran on testing and live" a fact
     * rather than a claim.
     */
    public function imageReference(StackService $entitlement): string
    {
        $repository = $entitlement->service->imageRepository();

        if (filled($entitlement->desired_digest)) {
            return $repository.'@'.$entitlement->desired_digest;
        }

        // Nothing has been built for this stack yet.
        return $repository.':'.($entitlement->edition ?: 'latest');
    }

    private function serviceBlock(StackService $entitlement): string
    {
        $template = $this->files->resolve($entitlement->service, BuildFiles::COMPOSE_SERVICE) ?? '';

        return $this->files->render($template, $this->composeScalars($entitlement) + [
            'container' => $entitlement->containerName(),
        ], [], composeEscape: true);
    }

    /**
     * @param  array{name: string, command: string|null, port: int|null, path: string|null}  $process
     */
    private function processBlock(StackService $entitlement, array $process): string
    {
        $template = $this->files->resolve($entitlement->service, BuildFiles::COMPOSE_PROCESS) ?? '';

        $ports = $process['port'] === null ? [] : [
            'ports:',
            '  - "127.0.0.1:'.$this->ports->assignProcess($entitlement, $process['name']).':'.$process['port'].'"',
        ];

        return $this->files->render($template, $this->composeScalars($entitlement) + [
            'name' => $process['name'],
            'container' => $entitlement->processContainerName($process['name']),
            // JSON is valid YAML, and quotes whatever the command holds.
            'command' => json_encode(['sh', '-c', (string) $process['command']], JSON_UNESCAPED_SLASHES),
        ], ['ports_block' => $ports], composeEscape: true);
    }

    /**
     * @return array<string, string|int>
     */
    private function composeScalars(StackService $entitlement): array
    {
        $service = $entitlement->service;
        $root = $this->rootPath($entitlement->stack);

        return [
            'slug' => $service->slug,
            'image' => $this->imageReference($entitlement),
            'host_port' => $this->ports->assign($entitlement),
            'container_port' => $this->containerPort($service->build_recipe),
            'env_file' => './env/'.$service->slug.'.env',
            // A host bind path rather than a named volume, so the weekly rsync
            // backup can read it directly.
            'storage_host' => $root.'/storage/'.$service->slug,
            'storage_container' => $this->storagePath($service->build_recipe),
            'network' => 'shared',
        ];
    }

    /**
     * A location per listening process: Reverb's websocket at /app, with
     * the upgrade headers and a long read timeout.
     *
     * @return list<string>
     */
    private function processLocations(StackService $entitlement): array
    {
        $lines = [];

        foreach ($entitlement->service->processList() as $process) {
            if ($process['port'] === null || $process['path'] === null) {
                continue;
            }

            $port = $this->ports->assignProcess($entitlement, $process['name']);

            $lines = [...$lines,
                'location '.$process['path'].' {',
                "    proxy_pass http://127.0.0.1:{$port};",
                '    proxy_http_version 1.1;',
                '    proxy_set_header Host              $host;',
                '    proxy_set_header X-Real-IP         $remote_addr;',
                '    proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;',
                '    proxy_set_header X-Forwarded-Proto $scheme;',
                '    proxy_set_header Upgrade           $http_upgrade;',
                '    proxy_set_header Connection        $connection_upgrade;',
                '    proxy_read_timeout 1d;',
                '}',
                '',
            ];
        }

        return $lines;
    }

    /**
     * Certificate issue and renewal both answer from this webroot.
     *
     * @return list<string>
     */
    private function acmeLocation(): array
    {
        return [
            'location ^~ /.well-known/acme-challenge/ {',
            '    root /var/www/acme;',
            '    default_type text/plain;',
            '}',
        ];
    }

    /** @return list<string> */
    private function proxyBody(int $port): array
    {
        return [
            "proxy_pass http://127.0.0.1:{$port};",
            'proxy_http_version 1.1;',
            '',
            'proxy_set_header Host              $host;',
            'proxy_set_header X-Real-IP         $remote_addr;',
            'proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;',
            'proxy_set_header X-Forwarded-Proto $scheme;',
            'proxy_set_header Upgrade           $http_upgrade;',
            'proxy_set_header Connection        $connection_upgrade;',
            '',
            'proxy_connect_timeout 600s;',
            'proxy_send_timeout 600s;',
            'proxy_read_timeout 600s;',
            'send_timeout 600s;',
        ];
    }

    /**
     * The maintenance page, set by the release runner for a destructive
     * migration. Generated rather than templated so it can never be broken
     * by an edit; on a domain without a certificate the plain variant is
     * linked instead.
     */
    private function maintenanceVhost(string $domain, bool $tls): string
    {
        $body = "    location / {\n"
            ."        # Maintenance window in progress — set by the release runner.\n"
            ."        root /var/www/maintenance;\n"
            ."        try_files /index.html =503;\n"
            ."    }\n";

        if (! $tls) {
            return "# Generated by the control plane. Maintenance page, until {$domain} has a certificate.\n"
                ."server {\n    listen 80;\n    listen [::]:80;\n    server_name {$domain};\n\n"
                .$this->indent($this->acmeLocation(), 4)."\n".$body."}\n";
        }

        return "# Generated by the control plane. Maintenance page.\n"
            ."server {\n    server_name {$domain};\n\n".$body."\n"
            ."    listen 443 ssl http2;\n    listen [::]:443 ssl http2;\n"
            ."    ssl_certificate /etc/letsencrypt/live/{$domain}/fullchain.pem;\n"
            ."    ssl_certificate_key /etc/letsencrypt/live/{$domain}/privkey.pem;\n"
            ."    ssl_protocols TLSv1.2 TLSv1.3;\n}\n\n"
            ."server {\n    listen 80;\n    listen [::]:80;\n    server_name {$domain};\n\n"
            .$this->indent($this->acmeLocation(), 4)."\n"
            ."    location / {\n        return 301 https://\$host\$request_uri;\n    }\n}\n";
    }

    /** @param  list<string>  $lines */
    private function indent(array $lines, int $spaces): string
    {
        if ($lines === []) {
            return '';
        }

        $pad = str_repeat(' ', $spaces);

        return implode("\n", array_map(fn (string $l) => $l === '' ? '' : $pad.$l, $lines))."\n";
    }

    private function network(): string
    {
        return (string) config('deploy.shared_network', 'pizza_shared');
    }

    /**
     * @return Collection<int, StackService>
     */
    private function enabledServices(Stack $stack): Collection
    {
        return StackService::query()
            ->with('service.files', 'stack.client')
            ->where('stack_id', $stack->id)
            ->where('enabled', true)
            ->get()
            ->sortBy(fn (StackService $s) => [$s->service->position, $s->service->slug])
            ->values();
    }

    private function containerPort(string $recipe): int
    {
        return $recipe === Service::RECIPE_NEXTJS ? 3000 : 80;
    }

    private function storagePath(string $recipe): string
    {
        return $recipe === Service::RECIPE_NEXTJS
            ? '/app/.next/cache'
            : '/var/www/html/storage/app';
    }

    /**
     * Quote only when the value needs it. Docker's env_file parser does not
     * strip quotes the way a shell does, so quoting everything would embed
     * literal quote characters in the values.
     */
    private function quote(string $value): string
    {
        return preg_match('/^[A-Za-z0-9_.:\/@=+-]*$/', $value) === 1
            ? $value
            : '"'.str_replace(['\\', '"'], ['\\\\', '\"'], $value).'"';
    }
}
